def routes():
    out = [
        "# Generated by docs/gen_routes.py. Hosts are <name>.<tailnet>.ts.net (TSDProxy terminates TLS).",
        "# Apps with their own logins and mobile apps (Plex, Emby, Immich, Nextcloud, Jellyseerr,",
        "# Audiobookshelf, Storyteller) skip Authentik so the apps keep working.",
        "http:", "  middlewares:", "    authentik:", "      forwardAuth:",
        "        address: http://authentik-server:9000/outpost.goauthentik.io/auth/traefik",
        "        trustForwardHeader: true",
        "        authResponseHeaders: [X-authentik-username, X-authentik-groups, X-authentik-email]",
        "  routers:",
    ]
    for name, (_, _, sso) in APPS.items():
        out += [f"    {name}:", f'      rule: Host(`{name}.{{{{ env "TS_TAILNET" }}}}`)',
                "      entryPoints: [web]", f"      service: {name}"]
        if sso:
            out.append("      middlewares: [authentik]")
    out.append("  services:")
    for name, (host, port, _) in APPS.items():
        out += [f"    {name}:", "      loadBalancer:", "        servers:", f"          - url: http://{host}:{port}"]
    return "\n".join(out) + "\n"


def tsdproxy_list():
    # TSDProxy 1.4.x list entries take a single "url" (no "ports:" block).
    out = ["# Generated by docs/gen_routes.py. One ts.net name per app, all handed to Traefik.", ""]
    for name in APPS:
        out += [f"{name}:", "  url: http://traefik:80", ""]
    return "\n".join(out)


